#!/usr/bin/env node
// Builds extension/dist/ (load-unpacked ready; zip this folder for a Chrome Web Store upload).
// Content-script matches come from events/*.json, so a new event config = rebuild, no code change.
import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { deflateSync, crc32 } from 'node:zlib';
import { build } from 'esbuild';

const root = new URL('../', import.meta.url);
const ext = new URL('extension/', root);
const dist = new URL('extension/dist/', root);

const files = (await readdir(new URL('events/', root))).filter((f) => f.endsWith('.json')).sort();
const events = await Promise.all(files.map(async (f) => JSON.parse(await readFile(new URL(`events/${f}`, root), 'utf8'))));
// Only what the content script needs (keeps the bundle small, no internal config leaks).
const slim = events.map(({ id, name, adapter, agendaUrl, match, pagination, timezone, venue, stageAliases, adapterOverrides, defaultDurationMin }) =>
  ({ id, name, adapter, agendaUrl, match, pagination, timezone, venue, stageAliases, adapterOverrides, defaultDurationMin }));
await writeFile(new URL('src/events.generated.js', ext), `// Generated by scripts/build-extension.js. Do not edit.\nexport default ${JSON.stringify(slim, null, 2)};\n`);

await rm(dist, { recursive: true, force: true });
await mkdir(new URL('icons/', dist), { recursive: true });
await build({
  entryPoints: [new URL('src/content.js', ext).pathname],
  bundle: true, format: 'iife', target: 'chrome110', minify: false, legalComments: 'none',
  outfile: new URL('content.js', dist).pathname, logLevel: 'warning',
});

const manifest = JSON.parse(await readFile(new URL('manifest.base.json', ext), 'utf8'));
manifest.version = JSON.parse(await readFile(new URL('package.json', root), 'utf8')).version;
manifest.content_scripts[0].matches = [...new Set(events.flatMap((e) => e.match || []))];
await writeFile(new URL('manifest.json', dist), JSON.stringify(manifest, null, 2) + '\n');

// Simple generated icon (calendar page) as PNG, no image dependencies.
function png(size) {
  const px = Buffer.alloc(size * size * 4);
  const set = (x, y, [r, g, b]) => { const i = (y * size + x) * 4; px[i] = r; px[i + 1] = g; px[i + 2] = b; px[i + 3] = 255; };
  const m = Math.max(1, Math.round(size / 10));
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const inside = x >= m && x < size - m && y >= m && y < size - m;
    if (!inside) { px[(y * size + x) * 4 + 3] = 0; continue; }
    const header = y < m + Math.round(size * 0.28);
    set(x, y, header ? [26, 115, 232] : [255, 255, 255]);
  }
  // grid dots
  const g = Math.round(size * 0.14);
  for (let r = 0; r < 3; r++) for (let c = 0; c < 3; c++) {
    const cx = Math.round(size * (0.3 + c * 0.2)), cy = Math.round(size * (0.52 + r * 0.14));
    for (let dy = 0; dy < Math.max(1, g / 2); dy++) for (let dx = 0; dx < Math.max(1, g / 2); dx++) set(cx + dx - 1, cy + dy - 1, [26, 115, 232]);
  }
  const raw = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) { raw[y * (size * 4 + 1)] = 0; px.copy(raw, y * (size * 4 + 1) + 1, y * size * 4, (y + 1) * size * 4); }
  const chunk = (type, data) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type), data]);
    const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td) >>> 0);
    return Buffer.concat([len, td, crc]);
  };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(size, 0); ihdr.writeUInt32BE(size, 4); ihdr[8] = 8; ihdr[9] = 6;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
}
for (const s of [16, 48, 128]) await writeFile(new URL(`icons/${s}.png`, dist), png(s));

console.log(`extension/dist built for ${events.length} event(s): ${manifest.content_scripts[0].matches.join(', ')}`);
